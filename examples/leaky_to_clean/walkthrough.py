"""Audit a leaky strategy, then its fixed version, with the Backtest Auditor library.

    python walkthrough.py            # print a summary and write the four reports to output/

Everything runs locally on synthetic prices. No data vendor, no network, no API key.
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from nba_auditor import audit_returns, check_code  # noqa: E402

import fixed_strategy  # noqa: E402
import leaky_strategy  # noqa: E402

OUT = HERE / "output"
BANNER = ("*Synthetic random-walk prices generated by walkthrough.py; dates are placeholders. Results are hypothetical "
          "and come from deliberate bugs (leaky version) or a strategy with no edge (fixed version).*\n\n")


def audit(module, name: str) -> dict:
    source = Path(module.__file__).read_text(encoding="utf-8")
    code_report = check_code(source)
    run = module.run()
    returns_report = audit_returns(
        run["returns"],
        turnover=run["turnover"],
        costs_bps=run.get("costs_bps"),  # None for the leaky version: the auditor charges its 10 bps default
        benchmark=run["benchmark"],
        n_trials=run["n_trials"],
    )
    return {"name": name, "code": code_report, "returns": returns_report}


def main(write: bool = True) -> list[dict]:
    results = [audit(leaky_strategy, "leaky"), audit(fixed_strategy, "fixed")]
    if write:
        OUT.mkdir(exist_ok=True)
        for i, r in enumerate(results):
            (OUT / f"{2 * i + 1}_{r['name']}_check_code.md").write_text(BANNER + r["code"].to_markdown(), encoding="utf-8")
            (OUT / f"{2 * i + 2}_{r['name']}_audit_returns.md").write_text(BANNER + r["returns"].to_markdown(), encoding="utf-8")
    for r in results:
        rules = ", ".join(f"{f.rule_id} ({f.severity}, line {f.line})" for f in r["code"].findings) or "none"
        print(f"\n== {r['name']} ==")
        print(f"check_code findings: {rules}")
        print(f"audit_returns verdict: {r['returns'].verdict}")
        for reason in r["returns"].reasons:
            print(f"  - {reason}")
    return results


if __name__ == "__main__":
    main()
